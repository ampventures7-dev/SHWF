// Helper to normalize strings for comparison & ID keys
const slugify = (str) =>
  str.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');

// Pre-compiled objects for high performance
export const INDIA_STATES = INDIA_STATES_AND_DISTRICTS.map((item) => ({
  id: `state-${slugify(item.name)}`,
  name: item.name,
  type: item.type
})).sort((a, b) => a.name.localeCompare(b.name));

const DISTRICTS_BY_STATE_MAP = {};
const DISTRICT_DETAILS_MAP = {};

INDIA_STATES_AND_DISTRICTS.forEach((item) => {
  const stateId = `state-${slugify(item.name)}`;
  const districtList = item.districts.map((dName) => {
    const dId = `dist-${slugify(item.name)}-${slugify(dName)}`;
    const obj = {
      id: dId,
      state_id: stateId,
      state_name: item.name,
      name: dName
    };
    DISTRICT_DETAILS_MAP[dId] = obj;
    return obj;
  }).sort((a, b) => a.name.localeCompare(b.name));

  DISTRICTS_BY_STATE_MAP[stateId] = districtList;
  // Also map by direct state name for fuzzy backend matching
  DISTRICTS_BY_STATE_MAP[item.name.toLowerCase()] = districtList;
});

/**
 * Get all 36 States & UTs
 */
export function getAllStates() {
  return INDIA_STATES;
}

/**
 * Get districts by State ID or State Name
 */
export function getDistrictsByState(stateIdOrName) {
  if (!stateIdOrName) return [];
  if (DISTRICTS_BY_STATE_MAP[stateIdOrName]) {
    return DISTRICTS_BY_STATE_MAP[stateIdOrName];
  }
  const normalized = stateIdOrName.toLowerCase();
  if (DISTRICTS_BY_STATE_MAP[normalized]) {
    return DISTRICTS_BY_STATE_MAP[normalized];
  }
  // Search by state UUID prefix match or state name match
  const foundState = INDIA_STATES.find(s => s.id === stateIdOrName || s.name.toLowerCase() === normalized);
  if (foundState && DISTRICTS_BY_STATE_MAP[foundState.id]) {
    return DISTRICTS_BY_STATE_MAP[foundState.id];
  }
  return [];
}

/**
 * Generate partner schools for a selected district
 */
export function getSchoolsForDistrict(districtId, districtName = '') {
  let name = districtName;
  if (!name && DISTRICT_DETAILS_MAP[districtId]) {
    name = DISTRICT_DETAILS_MAP[districtId].name;
  }
  if (!name) name = "District";

  const code = slugify(name).slice(0, 4).toUpperCase();
  return [
    {
      id: `sch-${slugify(name)}-001`,
      district_id: districtId,
      name: `St. Xavier Public School, ${name}`,
      school_code: `${code}01`
    },
    {
      id: `sch-${slugify(name)}-002`,
      district_id: districtId,
      name: `Government Model Health Academy, ${name}`,
      school_code: `${code}02`
    },
    {
      id: `sch-${slugify(name)}-003`,
      district_id: districtId,
      name: `Delhi Public School, ${name}`,
      school_code: `${code}03`
    },
    {
      id: `sch-${slugify(name)}-004`,
      district_id: districtId,
      name: `National Valley Senior Secondary School, ${name}`,
      school_code: `${code}04`
    }
  ];
}
